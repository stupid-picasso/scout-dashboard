function normalizeSpeciesName(s) {
  return String(s || '').toLowerCase()
    .replace(/[\u2642]/g, ' m').replace(/[\u2640]/g, ' f')
    .replace(/[^a-z0-9]+/g, ' ').trim().replace(/\s+/g, '-');
}
const NAME_TO_DEX = {};
Object.keys(DEX_NAMES).forEach(dex => { NAME_TO_DEX[normalizeSpeciesName(DEX_NAMES[dex])] = Number(dex); });
function resolveDexByName(name) {
  const norm = normalizeSpeciesName(name);
  if (NAME_TO_DEX[norm] != null) return NAME_TO_DEX[norm];
  const loose = norm.replace(/-/g, '');
  for (const key in NAME_TO_DEX) {
    if (key.replace(/-/g, '') === loose) return NAME_TO_DEX[key];
  }
  return null;
}


function cpFor(base, ivs, level) {
  const cpm = CPM[level];
  if (!cpm) return null;
  const atk = base[0] + ivs[0], def = base[1] + ivs[1], sta = base[2] + ivs[2];
  return Math.max(10, Math.floor((atk * Math.sqrt(def) * Math.sqrt(sta) * cpm * cpm) / 10));
}

function hpFor(base, staIV, level) {
  const cpm = CPM[level];
  if (!cpm) return null;
  return Math.max(10, Math.floor((base[2] + staIV) * cpm));
}

function statProductFor(base, ivs, level) {
  const cpm = CPM[level];
  const atk = (base[0] + ivs[0]) * cpm;
  const def = (base[1] + ivs[1]) * cpm;
  const hp = Math.max(10, Math.floor((base[2] + ivs[2]) * cpm));
  return atk * def * hp;
}

// Stardust cost to Power Up, keyed by the level a Pokemon is AT (i.e. the
// cost to go from this level to the next half-level up). This is the public,
// community-verified Power-Up cost table (the same one PokeGenie/CalcyIV use),
// cross-validated against 66 real (dust, CP/HP-solved level) pairs pulled from
// this app's own users' actual rosters \u2014 94% (62/66) landed the true level
// inside the range this table predicts.
//
// Earlier version of this table was WRONG: it assumed each dust cost spans
// only 2 half-levels (1 full level). In reality each dust cost spans 4
// half-levels (2 full levels), which made every prior lookup come out at
// roughly HALF the Pokemon's true level. Levels 41+ require Candy XL instead
// of regular Candy but the dust progression continues the same pattern.
const _DUST_TIER_START_LEVEL = [
  [1.0, 200], [3.0, 400], [5.0, 600], [7.0, 800], [9.0, 1000],
  [11.0, 1300], [13.0, 1600], [15.0, 1900], [17.0, 2200], [19.0, 2500],
  [21.0, 3000], [23.0, 3500], [25.0, 4000], [27.0, 4500], [29.0, 5000],
  [31.0, 6000], [33.0, 7000], [35.0, 8000], [37.0, 9000], [39.0, 10000],
  [41.0, 12000], [43.0, 15000], [45.0, 19000], [47.0, 22000], [49.0, 25000],
];

// dust value -> [levels...] that cost exactly that much to power up from.
// Each tier spans 4 consecutive half-levels starting at its listed level.
const _STARDUST_TO_LEVELS = (() => {
  const map = {};
  _DUST_TIER_START_LEVEL.forEach(([start, dust]) => {
    const levels = [0, 1, 2, 3].map(k => start + 0.5 * k);
    (map[dust] = map[dust] || []).push(...levels);
  });
  return map;
})();

// Reverses an OCR'd "Power Up" stardust cost into the small set of Pokemon
// levels that could produce it, undoing the lucky/shadow/purified cost
// multipliers first. Returns [] when the cost can't be matched (bad OCR,
// already-maxed Pokemon showing no Power Up button, or the ambiguous 15000
// plateau) \u2014 callers should treat an empty result as "no extra info",
// not as an error.
function levelsForPowerUpDust(observedDust, opts) {
  if (observedDust == null || !Number.isFinite(observedDust)) return [];
  opts = opts || {};
  let mult = 1;
  if (opts.lucky) mult *= 0.5;
  if (opts.shadow) mult *= 1.2;
  if (opts.purified) mult *= 0.9;
  const normalized = observedDust / mult;
  // In-game costs round to the nearest displayed value; allow a small
  // tolerance around the multiplier reversal rather than requiring exact
  // floating-point equality.
  let best = null, bestDiff = Infinity;
  for (const dustKey of Object.keys(_STARDUST_TO_LEVELS)) {
    const diff = Math.abs(Number(dustKey) - normalized);
    if (diff < bestDiff) { bestDiff = diff; best = dustKey; }
  }
  if (best == null || bestDiff > Number(best) * 0.05) return [];
  return _STARDUST_TO_LEVELS[best].slice();
}

// Brute-force every level/IV combo matching an observed CP and HP exactly.
// `hint` optionally narrows the result using what the in-game appraisal shows:
//   { stars: 0-4, maxed: ['atk','def','sta'] }
// Star tiers are total-IV bands, and a "maxed" bar means that stat is exactly
// 15. CP+HP alone often leaves dozens of spreads on low-CP Pokemon; the
// appraisal collapses that to one or two without needing exact printed numbers.
// `levelFilter`, if given, restricts the search to only those levels (e.g.
// the 1-2 levels implied by an OCR'd Power Up stardust cost via
// levelsForPowerUpDust) instead of every level 1-51 \u2014 the same kind of
// narrowing an appraisal gives, but derived from a number visible on every
// detail screen instead of a separate appraisal screen.
function solveIVs(base, cp, hp, hint, levelFilter) {
  const candidates = [];
  let levels = Object.keys(CPM).map(Number).sort((a, b) => a - b);
  if (Array.isArray(levelFilter) && levelFilter.length) {
    const allowed = new Set(levelFilter);
    levels = levels.filter(l => allowed.has(l));
  }
  for (const level of levels) {
    for (let staIV = 0; staIV <= 15; staIV++) {
      if (hpFor(base, staIV, level) !== hp) continue;
      for (let atkIV = 0; atkIV <= 15; atkIV++) {
        for (let defIV = 0; defIV <= 15; defIV++) {
          if (cpFor(base, [atkIV, defIV, staIV], level) === cp) {
            candidates.push({ level, atkIV, defIV, staIV });
          }
        }
      }
    }
  }
  return hint ? filterByAppraisal(candidates, hint) : candidates;
}

// Total-IV range for each appraisal star tier.
const STAR_BANDS = [[0, 22], [23, 29], [30, 36], [37, 44], [45, 45]];

function filterByAppraisal(candidates, hint) {
  if (!hint) return candidates;
  const band = Number.isInteger(hint.stars) ? STAR_BANDS[hint.stars] : null;
  const maxed = Array.isArray(hint.maxed) ? hint.maxed : [];
  const useMaxed = !!hint.maxedKnown;
  const out = candidates.filter(c => {
    if (band) {
      const total = c.atkIV + c.defIV + c.staIV;
      if (total < band[0] || total > band[1]) return false;
    }
    // A highlighted bar means that stat is 15; a bar the user did NOT mark must
    // therefore be below 15, which is what makes this so effective.
    if (useMaxed) {
      if (maxed.includes('atk') !== (c.atkIV === 15)) return false;
      if (maxed.includes('def') !== (c.defIV === 15)) return false;
      if (maxed.includes('sta') !== (c.staIV === 15)) return false;
    }
    return true;
  });
  // A hint that matches nothing is INFORMATION, not noise: it means the
  // appraisal contradicts the CP/HP, so one of the three was misread. Silently
  // returning the unfiltered set made the feature look like a no-op (a 3-star
  // hint on an 84-candidate Rookidee still gave 84) and told the user to add
  // more input when what they gave had been thrown away. Keep the full set so
  // nothing is lost, but flag the contradiction.
  if (!out.length) {
    const all = candidates.slice();
    all.hintMismatch = true;
    return all;
  }
  return out;
}

// Best possible stat product for a species at/under a league's CP cap, searched
// across ALL 4096 IV spreads. Using 15/15/15 as the reference is wrong for
// capped leagues: a lower-attack spread reaches a higher level under the cap and
// produces a HIGHER stat product, which made real Pokemon rank above 100%.
const _bestSPCache = new Map();
function bestStatProductUnderCap(base, capCP) {
  // base is an array [atk, def, sta] — an object-style key collides across species.
  const key = (Array.isArray(base) ? base.join('_') : [base.atk, base.def, base.sta].join('_')) + '|' + capCP;
  const hit = _bestSPCache.get(key);
  if (hit !== undefined) return hit;
  const levels = Object.keys(CPM).map(Number).sort((a, b) => a - b);
  let best = 0;
  for (let atkIV = 0; atkIV <= 15; atkIV++) {
    for (let defIV = 0; defIV <= 15; defIV++) {
      for (let staIV = 0; staIV <= 15; staIV++) {
        const ivs = [atkIV, defIV, staIV];
        // Levels ascend, so walk down from the top and take the first legal one.
        for (let i = levels.length - 1; i >= 0; i--) {
          if (cpFor(base, ivs, levels[i]) <= capCP) {
            const sp = statProductFor(base, ivs, levels[i]);
            if (sp > best) best = sp;
            break;
          }
        }
      }
    }
  }
  _bestSPCache.set(key, best);
  return best;
}

// This Pokemon's own best stat product at/under a league cap, searching all legal levels for its fixed IVs.
function ownBestStatProductUnderCap(base, ivs, capCP) {
  const levels = Object.keys(CPM).map(Number).sort((a, b) => a - b);
  for (let i = levels.length - 1; i >= 0; i--) {
    if (cpFor(base, ivs, levels[i]) <= capCP) return statProductFor(base, ivs, levels[i]);
  }
  return 0;
}

function rankPctForLeague(base, ivs, leagueKey) {
  const cap = LEAGUE_CAPS[leagueKey];
  const own = ownBestStatProductUnderCap(base, ivs, cap);
  const max = bestStatProductUnderCap(base, cap);
  if (!(max > 0)) return null;
  // Clamp: floating-point noise can nudge an optimal spread a hair over 100.
  return Math.min(100, (own / max) * 100);
}

